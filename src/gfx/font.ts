const ROWS = 7
const COLS = 5

function bits(ch: string): string {
  const g = GLYPHS[ch] ?? GLYPHS['?']
  return g.padEnd(ROWS * COLS, '.')
}

export const CHAR_W = 8

/** Draws text on an 8px grid like the NES did. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1): void {
  ctx.fillStyle = color
  let cx = x
  for (const ch of text.toUpperCase()) {
    const g = bits(ch)
    for (let r = 0; r < ROWS; r++) {
      for (let c = 0; c < COLS; c++) {
        if (g[r * COLS + c] === '#') ctx.fillRect(cx + (c + 1) * scale, y + r * scale, scale, scale)
      }
    }
    cx += CHAR_W * scale
  }
}

export function textWidth(text: string, scale = 1): number {
  return text.length * CHAR_W * scale
}

export function drawTextCentered(ctx: CanvasRenderingContext2D, text: string, cx: number, y: number, color: string, scale = 1): void {
  drawText(ctx, text, Math.round(cx - textWidth(text, scale) / 2), y, color, scale)
}

/** Glyph bitmap for drawing big brick-textured title letters. */
export function glyphPixels(ch: string): boolean[][] {
  const g = bits(ch)
  return Array.from({ length: ROWS }, (_, r) => Array.from({ length: COLS }, (_, c) => g[r * COLS + c] === '#'))
}
